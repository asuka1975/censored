import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { sourceWithoutTicks } from '../lib/hpc.mjs';
import { filterLines, parseLcov, percent } from '../lib/lcov.mjs';
import { decodeMappings, originalPosition } from '../lib/sourcemap.mjs';
import { hasRuntimeCode, lineHits } from '../ps-coverage.mjs';

describe('LCOV の読み取り', () => {
  it('ファイルごとに行の実行回数を取り出す', () => {
    const lcov = parseLcov('TN:\nSF:a.hs\nDA:1,3\nDA:2,0\nend_of_record\nSF:b.hs\nDA:5,1\nend_of_record\n');
    assert.equal(lcov.get('a.hs').get(1), 3);
    assert.equal(lcov.get('a.hs').get(2), 0);
    assert.equal(lcov.get('b.hs').get(5), 1);
  });

  it('同じ行が複数回現れたら多い方を採用する', () => {
    assert.equal(parseLcov('SF:a.hs\nDA:1,0\nDA:1,2\nend_of_record\n').get('a.hs').get(1), 2);
  });

  it('除外パターンに一致する行を分母から外す', () => {
    const lines = new Map([[1, 0], [2, 1]]);
    const out = filterLines(lines, '  deriving stock (Eq)\nf = 1\n', ['^\\s*deriving\\b']);
    assert.deepEqual([...out.keys()], [2]);
  });

  it('対象行がなければ 100% とする', () => {
    assert.equal(percent(0, 0), 100);
    assert.equal(percent(1, 4), 25);
  });
});

describe('ソースマップの復号', () => {
  it('VLQ を元の行と列へ復号する', () => {
    // 生成 0 列 → ソース 0, 行 0, 列 0 / 生成 4 列 → ソース 0, 行 1, 列 2
    const decoded = decodeMappings('AAAA,IACE');
    assert.deepEqual(decoded[0][0], { genCol: 0, src: 0, line: 1, col: 0 });
    assert.deepEqual(decoded[0][1], { genCol: 4, src: 0, line: 2, col: 2 });
  });

  it('行をまたいで相対値を積み上げる', () => {
    const decoded = decodeMappings('AAAA;AACA');
    assert.equal(decoded[1][0].line, 2);
  });

  it('指定位置の直前のセグメントを返す', () => {
    const decoded = decodeMappings('AAAA,IACE');
    assert.equal(originalPosition(decoded, 0, 3).line, 1);
    assert.equal(originalPosition(decoded, 0, 9).line, 2);
    assert.equal(originalPosition(decoded, 5, 0), null);
  });

  it('対応なしの区間を直前のソースへ対応づけない', () => {
    const decoded = decodeMappings('AAAA,K');
    assert.equal(originalPosition(decoded, 0, 3).line, 1);
    assert.equal(originalPosition(decoded, 0, 10), null);
  });

  it('対応なしの区間のあとの相対値を崩さない', () => {
    const decoded = decodeMappings('AAAA,K,KACE');
    assert.equal(originalPosition(decoded, 0, 12).line, 2);
  });
});

describe('V8 カバレッジの行への射影', () => {
  // 3 行の JS。2 行目は未実行の関数、3 行目は実行された関数。
  const js = 'var a = 1;\nvar f = function () { return 1; };\nvar g = function () { return 2; };\n';
  const map = { mappings: 'AAAA;AACA;AACA' };
  const start = (line) => js.split('\n').slice(0, line).join('\n').length + 1;

  it('未実行の関数の行を 0 回として報告する', () => {
    const ranges = [
      { startOffset: 0, endOffset: js.length, count: 1 },
      { startOffset: start(1), endOffset: start(2) - 1, count: 0 },
      { startOffset: start(2), endOffset: js.length - 1, count: 5 },
    ];
    const hits = lineHits(js, map, ranges).get(0);
    assert.equal(hits.get(2), 0);
    assert.equal(hits.get(3), 5);
  });

  it('モジュール読み込みで評価されるだけの行を分母に入れない', () => {
    const ranges = [
      { startOffset: 0, endOffset: js.length, count: 1 },
      { startOffset: start(1), endOffset: start(2) - 1, count: 0 },
    ];
    assert.equal(lineHits(js, map, ranges).get(0).has(1), false);
  });

  it('対応なしの区間を行に数えない', () => {
    const ranges = [
      { startOffset: 0, endOffset: js.length, count: 1 },
      { startOffset: 0, endOffset: 5, count: 3 },
    ];
    assert.equal(lineHits(js, { mappings: 'A' }, ranges).size, 0);
  });
});

describe('HPC の mix の読み取り', () => {
  it('ティックのないモジュールのソースを返す', () => {
    assert.equal(sourceWithoutTicks('Mix "src/Censored/Domain/Types.hs" 2026-11-01 17:24:58.72 UTC 1711177903 8 []\n'), 'src/Censored/Domain/Types.hs');
  });

  it('ティックのあるモジュールを実行コードなしと判定しない', () => {
    const mix = 'Mix "src/Censored/Domain/Limits.hs" 2026-11-01 17:24:58.72 UTC 3885337483 8 [(9:17-9:19,ExpBox False),(9:1-9:19,TopLevelBox ["maxBodyLength"])]\n';
    assert.equal(sourceWithoutTicks(mix), null);
  });

  it('関数名の中の空リストに惑わされない', () => {
    const mix = 'Mix "src/A.hs" 2026-11-01 17:24:58.72 UTC 1 8 [(1:1-1:2,TopLevelBox ["a"]),(1:3-1:4,TopLevelBox [])]\n';
    assert.equal(sourceWithoutTicks(mix), null);
  });
});

describe('実行コードの判定', () => {
  it('定数の定義を実行コードとして数える', () => {
    assert.equal(hasRuntimeCode('// Generated by purs\nvar answer = 42;\nexport {\n    answer\n};\n'), true);
  });

  it('型だけのモジュールの出力を実行コードとして数えない', () => {
    assert.equal(hasRuntimeCode('// Generated by purs version 0.15.16\nexport {};\n'), false);
  });

  it('再エクスポートだけのモジュールを実行コードとして数えない', () => {
    assert.equal(hasRuntimeCode('// Generated\nimport * as A from "../A/index.js";\nexport { x } from "../A/index.js";\n'), false);
  });

  it('関数を実行コードとして数える', () => {
    assert.equal(hasRuntimeCode('var f = function (x) {\n    return x;\n};\nexport { f };\n'), true);
  });
});
